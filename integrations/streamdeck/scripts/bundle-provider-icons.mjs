// Bundles OpenUsage provider logos into the Stream Deck plugin.
//
// The local HTTP API intentionally omits iconUrl, so we copy the icons at build
// time from the OpenUsage repo. The provider id returned by the API matches the
// icon file name, so the plugin maps a snapshot to its logo at runtime.
//
// Provider discovery (either edition's layout) lives in providers-source.mjs.
// Logos use fill="currentColor", so we tint them white to read on the dark faces.

import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import { collectProviders, pluginRoot } from "./providers-source.mjs";

const providersImgDir = join(pluginRoot, "ai.openusage.streamdeck.sdPlugin", "imgs", "providers");
const generatedFile = join(pluginRoot, "src", "generated", "provider-icons.ts");

const TINT = "#fafafa";

function tint(svg) {
	return svg.replace(/currentColor/g, TINT).replace(/\s+/g, " ").trim();
}

function toDataUri(svg) {
	return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

rmSync(providersImgDir, { recursive: true, force: true });
mkdirSync(providersImgDir, { recursive: true });

const icons = {};
for (const { id, svg } of collectProviders()) {
	const tinted = tint(svg);
	writeFileSync(join(providersImgDir, `${id}.svg`), tinted);
	icons[id] = toDataUri(tinted);
}

const ids = Object.keys(icons).sort();
const iconEntries = ids.map((id) => `\t${JSON.stringify(id)}: ${JSON.stringify(icons[id])},`).join("\n");

const out = `// AUTO-GENERATED by scripts/bundle-provider-icons.mjs — do not edit.
// Provider logos (tinted ${TINT}) bundled from the OpenUsage repo at build time.

/** providerId → white-tinted logo as an SVG data URI. */
export const PROVIDER_ICON_DATA: Record<string, string> = {
${iconEntries}
};
`;

mkdirSync(dirname(generatedFile), { recursive: true });
writeFileSync(generatedFile, out);

if (ids.length === 0) {
	console.warn("⚠ No provider icons found — checked Sources/OpenUsage/Resources/ProviderIcons and plugins/.");
} else {
	console.log(`Bundled ${ids.length} provider icons → ${generatedFile}`);
}
